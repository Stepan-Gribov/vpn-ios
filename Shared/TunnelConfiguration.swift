import Foundation

enum TunnelConfiguration {
    static func applying(to root: [String: Any], settings: AppSettings, isTURN: Bool,
                         restoreTURNRouting: Bool = false) -> [String: Any] {
        // Saved on-demand configurations may still contain the experimental
        // QUIC rule even after updating the app. Migrate them at runtime too.
        var result = restoreTURNRouting ? removingLegacyTURNHTTPSFallback(from: root) : root
        var inbounds = result["inbounds"] as? [[String: Any]] ?? []
        for index in inbounds.indices where inbounds[index]["protocol"] as? String == "tun" {
            var tunSettings = inbounds[index]["settings"] as? [String: Any] ?? [:]
            tunSettings["MTU"] = isTURN ? 1280 : min(1500, max(1280, settings.vpnMTU))
            inbounds[index]["settings"] = tunSettings
            let push = settings.splitTunneling?.pushNotifications?.enabled ?? false
            inbounds[index]["sniffing"] = [
                "enabled": settings.sniffingEnabled || settings.fakeDNSEnabled || push,
                "destOverride": ["http", "tls", "quic"] + (settings.fakeDNSEnabled ? ["fakedns"] : []),
                "routeOnly": (settings.splitTunneling?.mode ?? .disabled) != .disabled || push || (settings.routeOnly && !settings.fakeDNSEnabled),
                "metadataOnly": settings.fakeDNSEnabled && !settings.sniffingEnabled && !push,
            ]
        }
        result["inbounds"] = inbounds
        return SplitTunnelRouting.applying(to: result, settings: settings)
    }

    static func removingLegacyTURNHTTPSFallback(from root: [String: Any]) -> [String: Any] {
        guard var routing = root["routing"] as? [String: Any],
              var rules = routing["rules"] as? [[String: Any]] else { return root }
        var result = root
        let tags = ["in_proxy", "kindly-socks"]
        // Match only the exact rule generated by previous releases; keep user rules.
        rules.removeAll { rule in
            rule["type"] as? String == "field" && rule["network"] as? String == "udp" &&
            rule["port"] as? String == "443" && rule["outboundTag"] as? String == "block" &&
            rule["inboundTag"] as? [String] == tags && rule.count == 5
        }
        routing["rules"] = rules
        result["routing"] = routing
        return result
    }
}
